// ─── SWOT Analysis Types ─────────────────────────────────────────────────────

/**
 * A SWOT Analysis is the Minimum Viable Input for most diagnostics.
 *
 * Almost any stakeholder can produce a SWOT — even a rough gut-feel version
 * is enough to seed analytical context. Each item carries a confidence level
 * (how certain the author is) and a severity/impact score (how significant),
 * giving the system evidential grounding without requiring formal documents.
 *
 * SWOT items map naturally to diagnostic operations:
 *   - Strengths  → Capability Maturity (what we're good at)
 *   - Weaknesses → Friction Assessment, Gap Analysis (where we struggle)
 *   - Opportunities → Strategic Alignment, Initiative Impact (where to invest)
 *   - Threats → Risk Assessment, Compliance (what could hurt us)
 *
 * When no strategic plan, risk register, or other formal input exists,
 * a SWOT analysis is the recommended starting point. The NBA engine will
 * suggest providing one when diagnostics are available but no external
 * inputs have been supplied.
 */
export type SwotQuadrant = "strength" | "weakness" | "opportunity" | "threat";

export interface SwotItem {
  /** Unique ID */
  id: string;
  /** Which quadrant */
  quadrant: SwotQuadrant;
  /** Short title (e.g., "Strong digital fulfilment capability") */
  title: string;
  /** Longer description with context */
  description: string;
  /** How certain is the author about this item */
  confidence: "accurate" | "informed" | "estimate" | "unknown";
  /** Severity/impact on a 1–5 scale (1 = minor, 5 = critical) */
  severity: 1 | 2 | 3 | 4 | 5;
  /**
   * Optional scaffold element references — which capabilities, value streams,
   * activities, or roles does this item relate to? These allow the system to
   * anchor SWOT items to specific parts of the operating model.
   */
  relatedElementIds?: string[];
  /** Optional tags for categorisation (e.g., "technology", "regulatory", "people") */
  tags?: string[];
}

export interface SwotAnalysis {
  /** User-supplied label (e.g., "FY26 Strategic SWOT", "Quick Assessment") */
  label: string;
  /** ISO timestamp of when this was produced */
  producedAt: string;
  /** Overall confidence in the SWOT as a whole */
  overallConfidence: "accurate" | "informed" | "estimate" | "unknown";
  /** The items, grouped by quadrant for convenience */
  items: SwotItem[];
}

/** Helper: extract items by quadrant */
export function swotByQuadrant(swot: SwotAnalysis): Record<SwotQuadrant, SwotItem[]> {
  return {
    strength: swot.items.filter((i) => i.quadrant === "strength"),
    weakness: swot.items.filter((i) => i.quadrant === "weakness"),
    opportunity: swot.items.filter((i) => i.quadrant === "opportunity"),
    threat: swot.items.filter((i) => i.quadrant === "threat"),
  };
}

// ─── Confidence Propagation ─────────────────────────────────────────────────

/**
 * Compute the derived confidence for a diagnostic based on the external inputs
 * it consumed. This is called at diagnostic run time to freeze the confidence
 * into the artefact.
 *
 * Algorithm:
 *   1. No external inputs → "indicative" (purely model-inferred)
 *   2. All provided + accurate/informed → "high"
 *   3. Mix of provided and generated, or informed/estimate → "moderate"
 *   4. Mostly estimate/unknown → "low"
 */
export function computeDerivedConfidence(
  inputs: Array<{ provenance: InputProvenance; confidence: "accurate" | "informed" | "estimate" | "unknown" }>
): DiagnosticConfidence {
  if (inputs.length === 0) return "indicative";

  const weights: Record<string, number> = {
    accurate: 4,
    informed: 3,
    estimate: 2,
    unknown: 1,
  };
  const provenanceBonus: Record<InputProvenance, number> = {
    provided: 1,
    generated: 0,
  };

  let totalScore = 0;
  for (const input of inputs) {
    totalScore += weights[input.confidence] + provenanceBonus[input.provenance];
  }
  const avgScore = totalScore / inputs.length;

  // Thresholds: high ≥ 4, moderate ≥ 2.5, low ≥ 1.5, indicative below
  if (avgScore >= 4) return "high";
  if (avgScore >= 2.5) return "moderate";
  return "low";
}

// ─── Staleness Delta Computation ────────────────────────────────────────────

/**
 * Count scaffold elements by type for staleness delta comparison.
 */
export function countScaffoldElements(scaffold: any): Record<string, number> {
  const elements = scaffold?.elements ?? {};
  const counts: Record<string, number> = {};
  const keys = [
    "valueStreams", "activities", "capabilities", "roles",
    "informationObjects", "applicationFunctions", "controls",
    "metrics", "subActivityGraphs",
  ];
  for (const key of keys) {
    counts[key] = elements[key] ? Object.keys(elements[key]).length : 0;
  }
  return counts;
}

/**
 * Compute a human-readable staleness delta between the scaffold state when
 * a diagnostic was produced and the current scaffold state.
 *
 * Returns null if the scaffold hasn't changed in any meaningful way.
 */
export function computeStalenessDelta(
  atProduction: Record<string, number>,
  atCurrent: Record<string, number>
): StalenessDelta | null {
  const labels: Record<string, string> = {
    valueStreams: "value streams",
    activities: "stages",
    capabilities: "capabilities",
    roles: "roles",
    informationObjects: "information objects",
    applicationFunctions: "application functions",
    controls: "controls",
    metrics: "metrics",
    subActivityGraphs: "activity flow graphs",
  };

  const parts: string[] = [];
  for (const [key, label] of Object.entries(labels)) {
    const before = atProduction[key] ?? 0;
    const after = atCurrent[key] ?? 0;
    const diff = after - before;
    if (diff > 0) {
      parts.push(`${diff} new ${label}`);
    } else if (diff < 0) {
      parts.push(`${Math.abs(diff)} ${label} removed`);
    }
  }

  if (parts.length === 0) return null;

  return {
    atProduction,
    atCurrent,
    summary: `Model changed since this was run: ${parts.join(", ")}.`,
  };
}

