// ─── Diagnostic Artefact Types ───────────────────────────────────────────────

/**
 * Confidence level for a diagnostic result, derived from the quality of its
 * inputs at the time it was run. This creates an audit trail:
 *
 *   - "high": all required inputs are Provided with "accurate" or "informed" confidence
 *   - "moderate": inputs present but some are Generated or have "estimate" confidence
 *   - "low": key inputs missing or mostly "estimate"/"unknown" confidence
 *   - "indicative": no external inputs used; result is purely model-inferred
 *
 * This propagates through to board-facing outputs — a Risk Assessment run with
 * only a guess-level SWOT will carry "low" confidence, signalling the need for
 * better input data rather than hiding the uncertainty.
 *
 * @see FA SPAR Review (31 Mar 2026) — Epistemic Integrity / Confidence Propagation
 */
export type DiagnosticConfidence = "high" | "moderate" | "low" | "indicative";

/**
 * Quantified staleness delta — tells the user exactly what changed since this
 * diagnostic was produced. Turns "Re-run" from a maintenance chore into a
 * curiosity trigger: "5 new capabilities added since this was run."
 *
 * @see FA SPAR Review (31 Mar 2026) — Staleness as Curiosity Trigger
 */
export interface StalenessDelta {
  /** Element counts at the time the diagnostic was produced */
  atProduction: Record<string, number>;
  /** Element counts in the current scaffold */
  atCurrent: Record<string, number>;
  /** Human-readable summary of what changed */
  summary: string;
}

/**
 * Base interface for all diagnostic artefacts.
 * Every diagnostic output must record which scaffold version it was derived from.
 * This enables staleness detection (D-118 non-negotiable #3).
 */
export interface DiagnosticArtefactBase {
  /** Which diagnostic operation produced this */
  diagnosticId: string;
  /** Content hash of the scaffold when this was produced */
  scaffoldHash: string;
  /** ISO timestamp of when this diagnostic was run */
  producedAt: string;
  /** Whether this artefact is stale (scaffold has changed since production) */
  stale: boolean;

  // ── Confidence propagation ──

  /**
   * Derived confidence based on the quality and provenance of inputs used.
   * Computed at diagnostic run time, never stored as user input.
   */
  derivedConfidence: DiagnosticConfidence;
  /**
   * Which external inputs were consumed by this diagnostic at run time.
   * Records both the input ID and its provenance+confidence at the time,
   * so the audit trail is frozen even if inputs are later updated.
   */
  inputSnapshot: Array<{
    inputId: string;
    inputType: ExternalInputType;
    provenance: InputProvenance;
    confidence: "accurate" | "informed" | "estimate" | "unknown";
  }>;

  // ── Staleness detail ──

  /**
   * When stale === true, this contains the quantified delta explaining
   * exactly what changed in the scaffold since this diagnostic was produced.
   * Computed on demand by comparing scaffold element counts.
   */
  stalenessDelta?: StalenessDelta;
}

